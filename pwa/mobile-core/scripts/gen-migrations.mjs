// Bundles the SQL migrations with the app so the device can build its own database offline.
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '../../database/migrations');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const out = files.map((f) => ({ name: f, sql: fs.readFileSync(path.join(dir, f), 'utf8') }));
const dest = path.resolve(here, '../src/generated/migrations.ts');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, `// AUTO-GENERATED by scripts/gen-migrations.mjs - do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(out)};\n`);
console.log(`bundled ${out.length} migrations`);
